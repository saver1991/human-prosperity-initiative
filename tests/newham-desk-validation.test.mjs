import test from "node:test";
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {validateNewhamDeskSources} from "../research-tools/newham-desk-validation.mjs";
import {verifyNewhamDesk} from "../scripts/newham-desk-check.mjs";
const raw=await readFile("research/newham-pension-credit-desk-source-audit-v0.2.json","utf8");
const mapped=await readFile("research/F0-03-newham-indicator-feasibility-v0.2.csv","utf8");
const catalogue=await readFile("research/F0-03-indicator-catalog-v0.1.csv","utf8");
const run=(r=raw,m=mapped,c=catalogue)=>validateNewhamDeskSources(r,m,c);
test("F0-03 context validation preserves geography, licensing provenance and programme figures",()=>{
 const result=run();
 assert.equal(result.location.geoCode,"E09000025");
 assert.equal(result.contextFacts.length,4);
 assert.deepEqual(result.contextFacts.map(x=>x.value),[39,62,220,748590]);
 assert.equal(result.contextFacts[1].geography,"Great Britain");
 assert.equal(result.contextFacts[2].geography,"Newham");
 assert.equal(result.contextFacts.every(x=>x.denominatorValidatedForBenefitReceipt===false),true);
 assert.equal(result.indicatorReadiness.candidateCount,15);
 assert.equal(result.indicatorReadiness.locallyMeasuredWithApprovedDefinition,0);
 assert.equal(result.indicatorReadiness.primaryIndicator,"HPI-B-01");
 assert.equal(result.indicatorReadiness.localPrimaryValue,null);
 assert.equal(result.independentScientificApproval,false);
 assert.equal(result.outcomeValidForCausalInference,false);
 assert.equal(result.fieldworkAuthorised,false);
 assert.equal(result.measuredBeneficiaryImpact,false);
 assert.equal(result.thirdPartyDatasetDownloaded,false);
 assert.match(result.additionalityWarning,/Existing council programme/);
});
test("F0-03 validation rejects use of national take-up as a Newham receipt rate",()=>{
 const d=JSON.parse(raw);d.sourceItems[1].geography="Newham";
 assert.throws(()=>run(JSON.stringify(d)),/geography mismatch/);
 const a=JSON.parse(raw);a.verifiedLocalReceiptRate=62;
 assert.throws(()=>run(JSON.stringify(a)),/invented local eligible denominator/);
 const b=JSON.parse(raw);b.primaryDenominator=220;
 assert.throws(()=>run(JSON.stringify(b)),/invented local eligible denominator/);
 const c=JSON.parse(raw);c.sourceItems[2].denominatorValidatedForBenefitReceipt=true;
 assert.throws(()=>run(JSON.stringify(c)),/unapproved entitlement denominator/);
 const e=JSON.parse(raw);e.notExtractedSource.value=70;
 assert.throws(()=>run(JSON.stringify(e)),/distinct DWP local receipt series/);
});
test("F0-03 validation refuses council output as confirmed award and invented welfare effects",()=>{
 const a=JSON.parse(raw);a.sourceItems[2].value=250;
 assert.throws(()=>run(JSON.stringify(a)),/published source fact changed/);
 const b=JSON.parse(raw);b.measuredCausalEffect=0.12;
 assert.throws(()=>run(JSON.stringify(b)),/invented local eligible denominator/);
 const c=JSON.parse(raw);c.fieldStudyAuthorised=true;
 assert.throws(()=>run(JSON.stringify(c)),/unapproved study/);
 const d=JSON.parse(raw);d.sourceItems[3].sourceClass="official_area_context";
 assert.throws(()=>run(JSON.stringify(d)),/existing council service/);
});
test("All 15 proposed F0-03 instruments receive context-specific, non-validated statuses",()=>{
 const result=run();
 const status=result.indicatorReadiness.statuses;
 assert.equal(Object.values(status).reduce((a,b)=>a+b,0),15);
 assert.equal(status.candidate_primary_unmeasurable,1);
 assert.equal(status.context_only_not_indicator,1);
 assert.equal(status.blocked_ethics_and_denominator,1);
 const mistaken=mapped.replace('"HPI-B-01","candidate_primary_unmeasurable"','"HPI-B-01","not_measured"');
 assert.throws(()=>run(raw,mistaken),/cannot claim verified receipt/);
 const bad=mapped.replace('"HPI-A-03","context_only_not_indicator"','"HPI-A-03","not_measured"');
 assert.throws(()=>run(raw,bad),/local income deprivation mistaken/);
 const inflated=mapped.replace('"HPI-E-03","not_measured"','"HPI-E-03","context_only_not_indicator"');
 assert.throws(()=>run(raw,inflated),/council-reported benefit value/);
 const invalid=catalogue.replace("proposed_not_validated","validated");
 assert.throws(()=>run(raw,mapped,invalid),/scientifically approved/);
});
test("Published first-party Newham report has exact reproducibility and no phantom client data",async()=>{
 const result=await verifyNewhamDesk();
 assert.equal(result.status,"PASS");
 assert.equal(result.sourceFacts,4);
 assert.equal(result.primaryLocalOutcomeMeasured,0);
 const html=await readFile("dist/research/newham-pension-credit.html","utf8");
 const linked=await readFile("dist/research-newham-validation.json","utf8");
 const siteMap=await readFile("dist/sitemap.xml","utf8");
 assert.ok(siteMap.includes("/research/newham-pension-credit"));
 assert.ok(html.includes("Existing")===false||html.includes("Our Newham Money"));
 assert.ok(html.includes("No HPI intervention"));
 assert.equal(JSON.parse(linked).fieldworkAuthorised,false);
 assert.equal(JSON.parse(linked).independentScientificApproval,false);
});
